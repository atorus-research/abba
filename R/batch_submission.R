#' Submit programs for execution in series. Each program in a list will be submitted
#' after supplied wait function returns.
#'
#' @param prog_list A list of R program paths to execute
#' @param submit_func function that will be used to submit jobs
#' @param wait_func function that checks job status and returns when job finishes executing
#' @param ... arguments that will be passed to submit_func and wait_func functions
#'
#' @return list job IDs associated with executed programs
#' @noRd
#'
#' @examples \dontrun{
#' job_ids <- batch_submit_series(
#'   c("/mnt/work_drive/proj/comp/prot/task/development/prod/program/sdtm/dm.sas",
#'     "/mnt/work_drive/proj/comp/prot/task/development/prod/program/sdtm/ae.sas"))
#'  }
batch_submit_series <- function(prog_list,
                                submit_func=abba_rslauncher_submit_job_local,
                                wait_func=abba_rslauncher_watch_job_local,
                                ...) {
  job_ids <- list()

  # submit all programs to execute one by one
  for (prog in prog_list){
    job_id <- submit_func(prog, ...)
    job_ids <- c(job_ids, job_id)
    result <- wait_func(job_id, ...)
  }
  # return job ids generated by submitting programs for execution in workbench
  return(job_ids)
}

#' Submit programs for execution in parallel. Each program in a list will be submitted
#' at the same time.
#'
#' @param prog_list A list of R program paths to execute
#' @param submit_func function that will be used to submit jobs
#' @param wait_func function that checks job status and returns when job finishes executing
#' @param ... arguments that will be passed to submit_func and wait_func functions
#'
#' @return list job IDs associated with executed programs
#' @noRd
#'
#' @examples \dontrun{
#' job_ids <- batch_submit_parallel(
#'   c("/mnt/work_drive/proj/comp/prot/task/development/prod/program/tfl/t1_dm.sas",
#'     "/mnt/work_drive/proj/comp/prot/task/development/prod/program/tfl/t1_ae.sas"))
#'  }
batch_submit_parallel <- function(prog_list,
                                  submit_func=abba_rslauncher_submit_job_local,
                                  wait_func=abba_rslauncher_watch_job_local,
                                  ...) {
  # Submit jobs for the programs and wait until everything has been executed
  job_ids <- sapply(prog_list, function(x) submit_func(x, ...))

  # wait until all programs finish executing
  results <- wait_func(job_ids, ...)

  # return job ids generated by submitting programs for execution in workbench
  return(job_ids)
}

#' Submit programs for execution in order defined by structure of input list.
#' Programs inside sublists will be executed in parallel, and sublists themself
#' would be submitted sequentially.
#'
#' @param prog_list A list of R program paths to execute
#' @param submit_func function that will be used to submit jobs
#' @param wait_func function that checks job status and returns when job finishes executing
#' @param ... arguments that will be passed to submit_func and wait_func functions
#'
#' @return list job IDs associated with executed programs
#' @noRd
#'
#' @examples \dontrun{
#' job_ids <- submit_workbench_batch(list(
#'   c("/mnt/work_drive/proj/comp/prot/task/development/prod/program/sdtm/dm.sas"),
#'   c("/mnt/work_drive/proj/comp/prot/task/development/prod/program/sdtm/ae.sas"),
#'   c("/mnt/work_drive/proj/comp/prot/task/development/prod/program/tfl/t1_dm.sas",
#'     "/mnt/work_drive/proj/comp/prot/task/development/prod/program/tfl/t1_ae.sas")))
#'  }
submit_workbench_batch <- function(prog_list,
                                   submit_func=abba_rslauncher_submit_job_local,
                                   wait_func=abba_rslauncher_watch_job_local,
                                   ...) {
  # if prog_list is a data frame - convert it to a list of vectors acording to set rules
  prog_list_converted <- dataframe_to_batch_list(prog_list)
  # execute each item in the prog_list sequentially. Programs inside each list element,
  # which can also be a vector of program paths, will be executed in parallel
  job_ids <- lapply(
    prog_list_converted,
    function(x) batch_submit_parallel(x,
                                      submit_func=submit_func,
                                      wait_func=wait_func,
                                      ...)
    )
  return(unlist(job_ids))
}
